"""Aggregate results/runs/*.json into tables (results/summary.md) and figures.

Every number written here is computed from the saved run files; nothing is
typed in by hand. Mean ± sample std (ddof=1) over the 3 seeds.

Usage:  python scripts/make_report.py
"""

from __future__ import annotations

import json
import math
import sys
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from fedpriv.data import CLASSES  # noqa: E402

RUNS = ROOT / "results/runs"
FIG = ROOT / "results/figures"
# Categorical slots 1-3 of the dataviz reference palette (blue, orange, aqua) + muted ink.
C_FEDAVG, C_FEDPROX, C_CENTRAL, INK, MUTED = "#2a78d6", "#eb6834", "#1baf7a", "#0b0b0b", "#52514e"
ALPHAS = ["iid", "0.5", "0.1"]


def load_runs():
    runs = []
    for p in sorted(RUNS.glob("*.json")):
        with open(p) as f:
            runs.append(json.load(f))
    return runs


def key(r):
    c = r["config"]
    return (
        c.get("tag", ""),
        c["mode"],
        str(c.get("alpha")) if c["mode"] != "central" else "-",
        c.get("mu") if c["mode"] == "fedprox" else None,
        c.get("target_epsilon") if c["mode"] == "dp_fedavg" else None,
    )


def ms(vals, pct=True, nd=1):
    v = np.asarray(vals, dtype=float)
    f = 100.0 if pct else 1.0
    if len(v) == 1:
        return f"{f * v[0]:.{nd}f}"
    return f"{f * v.mean():.{nd}f} ± {f * v.std(ddof=1):.{nd}f}"


def ms3(vals):
    v = np.asarray(vals, dtype=float)
    return f"{v.mean():.3f} ± {v.std(ddof=1):.3f}" if len(v) > 1 else f"{v[0]:.3f}"


def label(k):
    tag, mode, alpha, mu, eps = k
    if mode == "central":
        return "Centralized (compute-matched)"
    a = "IID" if alpha == "iid" else f"Dir α={alpha}"
    if mode == "fedavg":
        return f"FedAvg, {a}"
    if mode == "fedprox":
        return f"FedProx (μ={mu}), {a}"
    return f"DP-FedAvg ε={eps}, {a}"


def metric_row(rs, split="test"):
    fin = [r[split]["final"] for r in rs]
    l10 = [r[split]["last10_mean"] for r in rs]
    return {
        "acc_final": ms([x["acc"] for x in fin]),
        "acc_l10": ms([x["acc"] for x in l10]),
        "f1_final": ms3([x["macro_f1"] for x in fin]),
        "f1_l10": ms3([x["macro_f1"] for x in l10]),
        "rec_l10": [ms([x["recall"][c] for x in l10]) for c in range(len(CLASSES))],
        "rec_final": [ms([x["recall"][c] for x in fin]) for c in range(len(CLASSES))],
    }


def main():
    runs = load_runs()
    groups = defaultdict(list)
    for r in runs:
        groups[key(r)].append(r)
    FIG.mkdir(parents=True, exist_ok=True)
    md = ["# Results summary (auto-generated by scripts/make_report.py)\n"]
    md.append("Test set = scenario-set files 13-15 (15,662 rows: Attack 11,295 / Natural 3,571 / "
              "NoEvents 796). Mean ± sample std over seeds (n shown). Accuracy and recall in %. "
              "\"last-10\" = mean of the metric over the last 10 rounds (or last 10 evaluation "
              "points for centralized).\n")

    # ---------------- main table ----------------
    order = [("", "central", "-", None, None)]
    for mode in ("fedavg", "fedprox"):
        for a in ALPHAS:
            order += [k for k in groups if k[0] == "" and k[1] == mode and k[2] == a]
    md.append("## Main results (test)\n")
    md.append("| Setting | n | Acc final | Acc last-10 | Macro-F1 final | Macro-F1 last-10 | "
              + " | ".join(f"Recall {c} (last-10)" for c in CLASSES) + " |")
    md.append("|---|---|---|---|---|---|" + "---|" * len(CLASSES))
    for k in order:
        if k not in groups:
            continue
        m = metric_row(groups[k])
        md.append(f"| {label(k)} | {len(groups[k])} | {m['acc_final']} | {m['acc_l10']} | {m['f1_final']} | "
                  f"{m['f1_l10']} | " + " | ".join(m["rec_l10"]) + " |")
    # Trivial reference: always predict the training-majority class (Attack).
    from fedpriv.data import load_dataset
    from fedpriv.metrics import scores

    d = load_dataset(ROOT / "data/raw/triple")
    maj = scores(d.test.y, np.full_like(d.test.y, np.bincount(d.train.y).argmax()))
    md.append(f"| Majority class (always 'Attack') | - | {100 * maj['acc']:.1f} | {100 * maj['acc']:.1f} | "
              f"{maj['macro_f1']:.3f} | {maj['macro_f1']:.3f} | "
              + " | ".join(f"{100 * x:.1f}" for x in maj["recall"]) + " |")

    # compute-matching check
    md.append("\n### Compute matching (sample-gradient passes per run)\n")
    md.append("| Setting | sample-gradient passes (mean) | N_train × R × E |")
    md.append("|---|---|---|")
    for k in order:
        if k in groups:
            r0 = groups[k][0]
            c = r0["config"]
            md.append(f"| {label(k)} | {np.mean([r['sample_grad_passes'] for r in groups[k]]):,.0f} | "
                      f"{r0['n_train'] * c['rounds'] * c['local_epochs']:,} |")

    # validation table + early stopping on validation (a third non-cherry-picked view)
    md.append("\n## Validation (files 11-12) and test at the validation-selected round\n")
    md.append("The round with the highest VALIDATION macro-F1 is selected per run (early stopping "
              "without looking at test); the test metrics at that round are reported.\n")
    md.append("| Setting | Val acc last-10 | Val macro-F1 last-10 | Selected round (mean) | "
              "Test acc @ selected | Test macro-F1 @ selected |")
    md.append("|---|---|---|---|---|---|")
    for k in order:
        if k in groups:
            m = metric_row(groups[k], "val")
            sel_r, sel_acc, sel_f1 = [], [], []
            for r in groups[k]:
                i = int(np.argmax([h["macro_f1"] for h in r["val"]["history"]]))
                sel_r.append(i + 1)
                sel_acc.append(r["test"]["history"][i]["acc"])
                sel_f1.append(r["test"]["history"][i]["macro_f1"])
            md.append(f"| {label(k)} | {m['acc_l10']} | {m['f1_l10']} | {np.mean(sel_r):.0f} | "
                      f"{ms(sel_acc)} | {ms3(sel_f1)} |")

    # ---------------- tuning ----------------
    tune = sorted([k for k in groups if k[0] == "tune"], key=lambda k: k[3])
    if tune:
        md.append("\n## FedProx μ tuning (α=0.1, seed 100, VALIDATION set)\n")
        md.append("| μ | Val acc last-10 | Val macro-F1 last-10 |")
        md.append("|---|---|---|")
        for k in tune:
            v = groups[k][0]["val"]["last10_mean"]
            md.append(f"| {k[3]} | {100 * v['acc']:.1f} | {v['macro_f1']:.3f} |")

    # ---------------- DP ----------------
    dptune = sorted([r for r in runs if r["config"].get("tag") == "dptune"],
                    key=lambda r: (r["config"]["lr"], r["config"]["max_grad_norm"]))
    if dptune:
        md.append("\n## DP hyper-parameter selection (schedule B, ε=3, seed 100, VALIDATION set)\n")
        md.append("| lr | clip C | Val acc last-10 | Val macro-F1 last-10 |")
        md.append("|---|---|---|---|")
        for r in dptune:
            v = r["val"]["last10_mean"]
            md.append(f"| {r['config']['lr']} | {r['config']['max_grad_norm']} | {100 * v['acc']:.1f} | "
                      f"{v['macro_f1']:.3f} |")

    dp_blocks = {}
    for tag, ref_tag, title in (
        ("", "", "A1: R=100 x E=2, lr 0.05, C=1 (main-grid hyper-parameters)"),
        ("short", "short", "B: R=30 x E=1, lr 0.2, C=20 (selected on validation)"),
        ("c20", "", "A2: R=100 x E=2, lr 0.2, C=20 (B's selection reused)"),
    ):
        dp = sorted([k for k in groups if k[1] == "dp_fedavg" and k[0] == tag], key=lambda k: k[4])
        ref = (ref_tag, "fedavg", "0.5", None, None)
        if not dp:
            continue
        dp_blocks[tag] = (dp, ref, title)
        md.append(f"\n## Privacy-utility, schedule {title}; DP-FedAvg, Dir α=0.5, δ=1e-5, test\n")
        md.append("| Target ε | Achieved ε (worst client, mean over seeds) | Noise multiplier σ (range over clients) | "
                  "Acc last-10 | Macro-F1 final | Macro-F1 last-10 | Recall Natural last-10 | "
                  "Recall NoEvents last-10 | n |")
        md.append("|---|---|---|---|---|---|---|---|---|")
        for k in dp:
            rs = groups[k]
            m = metric_row(rs)
            eps = [r["epsilon_max"] for r in rs]
            sig = [s for r in rs for s in r["noise_multipliers"]]
            eps_s = "∞ (clip only, σ=0)" if math.isinf(eps[0]) else f"{np.mean(eps):.2f}"
            md.append(f"| {'∞' if math.isinf(k[4]) else k[4]} | {eps_s} | {min(sig):.2f}-{max(sig):.2f} | "
                      f"{m['acc_l10']} | {m['f1_final']} | {m['f1_l10']} | {m['rec_l10'][1]} | {m['rec_l10'][2]} | "
                      f"{len(rs)} |")
        if ref in groups:
            m = metric_row(groups[ref])
            md.append(f"| non-private FedAvg (lr {groups[ref][0]['config']['lr']}, no clip, no noise) | - | - | {m['acc_l10']} | {m['f1_final']} | {m['f1_l10']} | "
                      f"{m['rec_l10'][1]} | {m['rec_l10'][2]} | {len(groups[ref])} |")
        md.append(f"| majority class | - | - | {100 * maj['acc']:.1f} | {maj['macro_f1']:.3f} | "
                  f"{maj['macro_f1']:.3f} | 0.0 | 0.0 | - |")

    # ---------------- leakage check ----------------
    lk = ROOT / "results/leakage_check.json"
    if lk.exists():
        L = json.load(open(lk))
        md.append("\n## Leakage check: split by scenario set vs random rows (centralized, 3 seeds)\n")
        md.append("| Model | Split | Test acc | Test macro-F1 |")
        md.append("|---|---|---|---|")
        for mname in ("mlp", "rf"):
            for split in ("set", "random_row"):
                rows = [x["last10_mean"] if mname == "mlp" else x for x in L[mname][split]]
                md.append(f"| {'MLP (last-10 epochs)' if mname == 'mlp' else 'RandomForest-200'} | "
                          f"{'by scenario set (files 13-15)' if split == 'set' else 'random 20% of rows'} | "
                          f"{ms([x['acc'] for x in rows])} | {ms3([x['macro_f1'] for x in rows])} |")

    gnp = ROOT / "results/grad_norms.json"
    if gnp.exists():
        G = json.load(open(gnp))
        md.append("\n## Per-sample gradient norms by class (non-private centralized training, 3 seeds)\n")
        md.append("Median per-sample gradient L2 norm on 4,000 training rows, and the mean factor min(1, C/norm) "
                  "by which clipping at C=1 scales a sample's gradient (mean over seeds).\n")
        md.append("| Epochs trained | " + " | ".join(f"{c} median norm | {c} clip factor (C=1)" for c in CLASSES) + " |")
        md.append("|---|" + "---|---|" * len(CLASSES))
        for e in sorted({r["epochs"] for r in G}):
            rows = [r for r in G if r["epochs"] == e]
            md.append(f"| {e} | " + " | ".join(
                f"{np.mean([r[c]['median'] for r in rows]):.2f} | {np.mean([r[c]['mean_shrink_factor_C1'] for r in rows]):.2f}"
                for c in CLASSES) + " |")

    # ---------------- wall time ----------------
    tot = sum(r["wall_time_s"] for r in runs)
    md.append("\n## Wall-clock time\n")
    md.append("| Group | runs | total minutes | minutes per run (mean) |")
    md.append("|---|---|---|---|")
    by_mode = defaultdict(list)
    for r in runs:
        by_mode[(r["config"].get("tag", "") + " " + r["config"]["mode"]).strip()].append(r["wall_time_s"])
    for m, ts in sorted(by_mode.items()):
        md.append(f"| {m} | {len(ts)} | {sum(ts) / 60:.1f} | {np.mean(ts) / 60:.2f} |")
    extra = json.load(open(lk))["wall_time_s"] if lk.exists() else 0.0
    md.append(f"| leakage check | - | {extra / 60:.1f} | - |")
    md.append(f"| **all experiments** | {len(runs)} | **{(tot + extra) / 60:.1f}** | - |")
    env = runs[0]["environment"] if runs else {}
    md.append(f"\nEnvironment: {json.dumps(env)}\n")

    (ROOT / "results/summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(md))

    # ---------------- figures ----------------
    plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                         "xtick.color": MUTED, "ytick.color": MUTED, "axes.spines.top": False,
                         "axes.spines.right": False, "figure.facecolor": "#fcfcfb", "axes.facecolor": "#fcfcfb"})

    def curves(k, metric):
        H = np.array([[h[metric] for h in r["test"]["history"]] for r in groups[k]])
        return H.mean(0), H.std(0, ddof=1) if len(H) > 1 else np.zeros(H.shape[1])

    # Fig 1: accuracy and macro-F1 vs round, one column per alpha
    fig, axes = plt.subplots(2, 3, figsize=(11, 6), sharex=True, sharey="row")
    for j, a in enumerate(ALPHAS):
        for i, metric in enumerate(("acc", "macro_f1")):
            ax = axes[i, j]
            series = [(("", "central", "-", None, None), "Centralized (compute-matched)", C_CENTRAL)]
            series += [(k, "FedAvg", C_FEDAVG) for k in groups if k[:3] == ("", "fedavg", a)]
            series += [(k, f"FedProx μ={k[3]}", C_FEDPROX) for k in groups if k[:3] == ("", "fedprox", a)]
            for k, lab, col in series:
                if k not in groups:
                    continue
                mu_, sd = curves(k, metric)
                x = np.arange(1, len(mu_) + 1)
                f = 100 if metric == "acc" else 1
                ax.plot(x, f * mu_, color=col, lw=1.6, label=lab)
                ax.fill_between(x, f * (mu_ - sd), f * (mu_ + sd), color=col, alpha=0.15, lw=0)
            ax.axvspan(91, 100, color=MUTED, alpha=0.08, lw=0)
            ax.axhline(100 * maj["acc"] if metric == "acc" else maj["macro_f1"], color=MUTED, ls="--", lw=1.0,
                       label="Majority class ('Attack')")
            ax.grid(axis="y", color="#e5e4e0", lw=0.6)
            if i == 0:
                ax.set_title("IID" if a == "iid" else f"Dirichlet α={a}", color=INK)
            if j == 0:
                ax.set_ylabel("Test accuracy (%)" if metric == "acc" else "Test macro-F1")
            if i == 1:
                ax.set_xlabel("Round (centralized: every 2 epochs)")
    axes[1, 0].legend(frameon=False, loc="lower right", fontsize=7)
    fig.suptitle("Test accuracy and macro-F1 per round (mean ± std band, 3 seeds; grey column = last-10 window)",
                 color=INK)
    fig.tight_layout()
    fig.savefig(FIG / "curves_by_alpha.png", dpi=150)
    plt.close(fig)

    # Fig 2: privacy-utility (macro-F1 only: accuracy sits at the majority rate and hides collapse)
    if dp_blocks:
        fig, ax = plt.subplots(figsize=(6.4, 3.8))
        xlabels = ["ε=1", "ε=3", "ε=8", "ε=∞\n(clip only)", "non-private\n(no clip)"]
        for (tag, (dp, ref, title)), col in zip(dp_blocks.items(), (C_FEDAVG, C_FEDPROX, C_CENTRAL)):
            ks = dp + ([ref] if ref in groups else [])
            ys = [np.mean([r["test"]["last10_mean"]["macro_f1"] for r in groups[k]]) for k in ks]
            es = [np.std([r["test"]["last10_mean"]["macro_f1"] for r in groups[k]], ddof=1) for k in ks]
            xs = np.arange(len(ks)) + {"": -0.08, "short": 0.0, "c20": 0.08}[tag]
            ax.errorbar(xs, ys, yerr=es, color=col, marker="o", ms=6, lw=1.6, capsize=3,
                        label="Schedule " + title.split(" (")[0])
        ax.axhline(maj["macro_f1"], color=MUTED, ls="--", lw=1.0, label="Majority class ('Attack')")
        ax.set_xticks(range(len(xlabels)))
        ax.set_xticklabels(xlabels, fontsize=8)
        ax.set_ylabel("Test macro-F1 (last-10-round mean)")
        ax.set_xlabel("Per-client record-level privacy budget (δ=1e-5)")
        ax.grid(axis="y", color="#e5e4e0", lw=0.6)
        ax.legend(frameon=False, fontsize=7, loc="upper left")
        ax.set_title("Privacy-utility, DP-FedAvg, Dirichlet α=0.5 (mean ± std, 3 seeds)", color=INK, fontsize=9)
        fig.tight_layout()
        fig.savefig(FIG / "privacy_utility.png", dpi=150)
        plt.close(fig)

    # Fig 3: per-class recall (last-10 mean)
    sel = [("", "central", "-", None, None)] + [k for k in order if k[1] in ("fedavg", "fedprox")]
    sel = [k for k in sel if k in groups]
    fig, ax = plt.subplots(figsize=(10, 3.6))
    width = 0.8 / len(CLASSES)
    cols = [C_FEDAVG, C_FEDPROX, C_CENTRAL]
    for c in range(len(CLASSES)):
        means = [np.mean([100 * r["test"]["last10_mean"]["recall"][c] for r in groups[k]]) for k in sel]
        sds = [np.std([100 * r["test"]["last10_mean"]["recall"][c] for r in groups[k]], ddof=1) for k in sel]
        xpos = np.arange(len(sel)) + (c - 1) * width
        ax.bar(xpos, means, width * 0.92, yerr=sds, color=cols[c], label=CLASSES[c], capsize=2,
               error_kw={"elinewidth": 0.8, "ecolor": MUTED})
    ax.set_xticks(np.arange(len(sel)))
    ax.set_xticklabels([label(k).replace(" (compute-matched)", "\n(compute-matched)").replace(", ", "\n")
                        for k in sel], fontsize=7)
    ax.set_ylabel("Test recall (%), last-10 mean")
    ax.set_ylim(0, 115)
    ax.set_yticks(range(0, 101, 20))
    ax.grid(axis="y", color="#e5e4e0", lw=0.6)
    ax.legend(frameon=False, ncol=3, loc="upper right")
    ax.set_title("Per-class recall (mean ± std, 3 seeds)", color=INK)
    fig.tight_layout()
    fig.savefig(FIG / "per_class_recall.png", dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
